  const ATTRS = [
    ["data-i18n", null],
    ["data-i18n-ph", "placeholder"],
    ["data-i18n-aria", "aria-label"],
    ["data-i18n-title", "title"],
    ["data-i18n-content", "content"],
  ];
  const original = new Map(); // element -> { attr: uzbekValue }

  function capture() {
    ATTRS.forEach(([data, attr]) => {
      document.querySelectorAll(`[${data}]`).forEach((el) => {
        const rec = original.get(el) || {};
        rec[data] = attr ? el.getAttribute(attr) : el.innerHTML;
        original.set(el, rec);
      });
    });
  }

  function apply() {
    document.documentElement.lang = lang;
    ATTRS.forEach(([data, attr]) => {
      document.querySelectorAll(`[${data}]`).forEach((el) => {
        const key = el.getAttribute(data);
        const value = lang === "uz" ? (original.get(el) || {})[data] : PAGE[lang][key];
        if (value == null) return;
        if (attr) el.setAttribute(attr, value);
        else if (el.innerHTML !== value) el.innerHTML = value;
      });
    });
    document.querySelectorAll("[data-lang-select]").forEach((s) => (s.value = lang));
  }

  function setLang(next) {
    if (!LANGS.includes(next) || next === lang) return;
    lang = next;
    try { localStorage.setItem(STORE, lang); } catch (e) { /* ignore */ }
    apply();
    document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
  }

  document.addEventListener("DOMContentLoaded", () => {
    capture();
    apply();
    document.querySelectorAll("[data-lang-select]").forEach((s) =>
      s.addEventListener("change", () => setLang(s.value))
    );
    document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
    const wait = document.getElementById("i18n-wait");
    if (wait) wait.remove();
  });

  window.I18N = {
    get lang() { return lang; },
    t, fmt, unit, pts, setLang,
    keys: { PAGE, MSG }, // exposed for checks
  };
