  function fill(str, vars) {
    return vars ? str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : str;
  }

  function fmt(n) {
    return Number(n).toLocaleString(lang === "en" ? "en-US" : "ru-RU");
  }

  // Unit word for a number of points, with Russian plural forms.
  function unit(n) {
    if (lang === "en") return "pts";
    if (lang === "uz") return "ball";
    const a = Math.abs(n) % 100, b = a % 10;
    if (a > 10 && a < 20) return "баллов";
    if (b === 1) return "балл";
    if (b >= 2 && b <= 4) return "балла";
    return "баллов";
  }

  const pts = (n) => fmt(n) + " " + unit(n);

  function t(key, vars) {
    let s = (MSG[lang] && MSG[lang][key]) ?? MSG.en[key] ?? key;
    if (vars && "n" in vars && !("p" in vars)) vars = Object.assign({ p: pts(vars.n) }, vars);
    return fill(s, vars);
  }

